const search = document.getElementById("search");
const result = document.getElementById("result");
const foodName = document.getElementById("foodName");
const circle = document.getElementById("circle");
const portion = document.getElementById("portion");
const notFound = document.getElementById("notFound");


search.addEventListener("input", function () {

    const query = search.value
        .trim()
        .toLowerCase();

    if (query === "") {
        result.classList.add("hidden");
        notFound.classList.add("hidden");
        return;
    }

    const food = Object.keys(foods).find(function (name) {
        return name.includes(query);
    });

    if (!food) {
        result.classList.add("hidden");
        notFound.classList.remove("hidden");
        return;
    }

    const data = foods[food];

    foodName.textContent = food;

    circle.className = "circle " + data.color;

    if (data.portion) {
        portion.textContent = data.portion;
        portion.classList.remove("hidden");
    } else {
        portion.textContent = "";
        portion.classList.add("hidden");
    }

    result.classList.remove("hidden");
    notFound.classList.add("hidden");

});
